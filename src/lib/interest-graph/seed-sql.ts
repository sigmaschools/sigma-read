/**
 * Builds drizzle/0011_interest_graph.sql: the tables plus the seed topic map from taxonomy.ts.
 * Regenerate with `npx tsx scripts/gen-topic-seed.ts`; taxonomy.test.ts checks the file is current.
 *
 * Seeds use ON CONFLICT DO NOTHING, so the file stays idempotent and never overwrites a topic
 * an admin has since edited. New taxonomy entries for an applied database go in a new migration.
 */

import { flattenTaxonomy, RELATED } from "./taxonomy";
import { matchKey, normalizePhrase } from "./resolve";

const DDL = `-- Interest graph phase 1: shared topic map, per-article tags, and the append-only signal log.
-- Generated by scripts/gen-topic-seed.ts from src/lib/interest-graph/taxonomy.ts. Do not edit by hand.

CREATE TABLE IF NOT EXISTS topics (
  id serial PRIMARY KEY,
  slug text NOT NULL,
  label text NOT NULL,
  parent_slug text,
  domain text NOT NULL,
  safety_status varchar(20) DEFAULT 'approved' NOT NULL,
  wikidata_id text,
  created_at timestamp DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS topics_slug_unique ON topics (slug);

CREATE TABLE IF NOT EXISTS topic_aliases (
  id serial PRIMARY KEY,
  alias text NOT NULL,
  topic_slug text NOT NULL,
  origin varchar(20) DEFAULT 'seed' NOT NULL,
  created_at timestamp DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS topic_aliases_alias_unique ON topic_aliases (alias);

CREATE TABLE IF NOT EXISTS topic_relations (
  id serial PRIMARY KEY,
  from_slug text NOT NULL,
  to_slug text NOT NULL,
  relation varchar(20) DEFAULT 'related' NOT NULL,
  weight real DEFAULT 1 NOT NULL,
  origin varchar(20) DEFAULT 'seeded' NOT NULL,
  created_at timestamp DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS topic_relations_pair_unique ON topic_relations (from_slug, to_slug, relation);

CREATE TABLE IF NOT EXISTS article_topics (
  id serial PRIMARY KEY,
  article_cache_id integer NOT NULL,
  topic_slug text NOT NULL,
  role varchar(10) DEFAULT 'primary' NOT NULL,
  created_at timestamp DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS article_topics_article_topic_unique ON article_topics (article_cache_id, topic_slug);

CREATE TABLE IF NOT EXISTS interest_signals (
  id serial PRIMARY KEY,
  student_id integer NOT NULL,
  topic_slug text,
  phrase text,
  signal_type varchar(30) NOT NULL,
  weight real NOT NULL,
  source_app varchar(30) DEFAULT 'sigmaread' NOT NULL,
  source_ref text,
  created_at timestamp DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS interest_signals_source_unique ON interest_signals (student_id, signal_type, source_ref);
CREATE INDEX IF NOT EXISTS interest_signals_student_time_idx ON interest_signals (student_id, created_at);
`;

const q = (s: string | null) => (s === null ? "NULL" : `'${s.replace(/'/g, "''")}'`);

export function topicSeedSql(): string {
  const topics = flattenTaxonomy();
  const topicRows = topics.map(t => `  (${q(t.slug)}, ${q(t.label)}, ${q(t.parentSlug)}, ${q(t.domain)})`);

  // Aliases are stored normalized; skip any that match a topic's own slug or label anyway
  const own = new Set(topics.flatMap(t => [matchKey(t.slug.replace(/-/g, " ")), matchKey(t.label)]));
  const keys = new Set<string>();
  const aliasRows = new Map<string, string>();
  for (const t of topics) {
    for (const a of t.aliases) {
      const key = matchKey(a);
      if (!key || own.has(key) || keys.has(key)) continue;
      keys.add(key);
      aliasRows.set(normalizePhrase(a), t.slug);
    }
  }

  const slugs = new Set(topics.map(t => t.slug));
  const relationRows = RELATED.filter(([a, b]) => slugs.has(a) && slugs.has(b))
    .map(([a, b]) => `  (${q(a)}, ${q(b)})`);

  return [
    DDL,
    `INSERT INTO topics (slug, label, parent_slug, domain) VALUES\n${topicRows.join(",\n")}\nON CONFLICT (slug) DO NOTHING;`,
    "",
    `INSERT INTO topic_aliases (alias, topic_slug) VALUES\n${[...aliasRows].map(([k, s]) => `  (${q(k)}, ${q(s)})`).join(",\n")}\nON CONFLICT (alias) DO NOTHING;`,
    "",
    `INSERT INTO topic_relations (from_slug, to_slug) VALUES\n${relationRows.join(",\n")}\nON CONFLICT (from_slug, to_slug, relation) DO NOTHING;`,
    "",
  ].join("\n");
}
